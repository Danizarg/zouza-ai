#!/usr/bin/env node
// Generates supabase/migrations/0008_banned_terms.sql from the English and Spanish lists of
// "List of Dirty, Naughty, Obscene, and Otherwise Bad Words" (LDNOOBW), CC BY 4.0:
// https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words
//
//   node scripts/supabase/banned-terms.mjs > supabase/migrations/0008_banned_terms.sql
//
// Terms are lowercased and stripped of accents (the filter compares unaccented text). ALLOW lists
// entries that are ordinary words in a property listing or everyday Spanish and must not be blocked.

const SOURCES = {
  en: "https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/master/en",
  es: "https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/master/es",
};

const ALLOW = new Set([
  "asno", "big black", "concha", "girl on", "infierno", "lolita", "maciza", "maldito", "martillo",
  "negro", "pinche", "pis", "sexy", "snatch", "suck", "sucks", "tied up", "tight white", "trio",
]);

const normalize = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/\s+/g, " ").trim();

const terms = new Set();
for (const [lang, url] of Object.entries(SOURCES)) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${lang}: HTTP ${res.status}`);
  for (const line of (await res.text()).split(/\r?\n/)) {
    const t = normalize(line);
    if (t.length >= 3 && !ALLOW.has(t) && /^[a-z0-9 '\-]+$/.test(t)) terms.add(t);
  }
}

const sorted = [...terms].sort();
const values = sorted.map((t) => `  ('${t.replace(/'/g, "''")}')`).join(",\n");
process.stdout.write(`-- 0008 seed for the word filter (generated by scripts/supabase/banned-terms.mjs; do not edit by hand).
-- Source: LDNOOBW English and Spanish lists, CC BY 4.0,
-- https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words
-- Allowed (removed) terms: ${[...ALLOW].sort().join(", ") || "none"}.
insert into private.banned_terms (term) values
${values}
on conflict (term) do nothing;
`);
console.error(`${sorted.length} terms`);
